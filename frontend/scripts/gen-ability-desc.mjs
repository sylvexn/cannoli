#!/usr/bin/env bun
/**
 * Generates the ability → short-description map used by AbilityChip tooltips
 * (Matchup Center, draft board, pokemon detail, team roster, …).
 *
 * RUN WITH BUN (`bun scripts/gen-ability-desc.mjs`).
 *
 * DATA SOURCE: the local Showdown checkout's text data
 * (`showdown/server/data/text/abilities.ts`), which carries a concise
 * `shortDesc` for every ability — the canonical wording Showdown shows in-game.
 *
 * MERGE POLICY (existing-wins): the hand-tuned terse entries already in
 * `src/lib/abilities.ts` are PRESERVED; Showdown's `shortDesc` only fills the
 * gaps. So curated wording stays, and abilities that were previously missing
 * (Quark Drive, Berserk, Vital Spirit, Toxic Debris, …) stop reading
 * "No description available."
 *
 * Usage: bun scripts/gen-ability-desc.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ABILITY_DESC as CURATED } from '../src/lib/abilities.ts';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const REPO_ROOT = resolve(ROOT, '..');

// 1. Load Showdown's ability text and extract the object literal
// The file is `export const AbilitiesText: {...} = { <literal> };`. Slice from
// the first `{` after the `=` to the final `}`, then eval it as plain JS (it's
// trusted local data with unquoted keys, so JSON.parse won't do).

const SRC = resolve(REPO_ROOT, 'showdown/server/data/text/abilities.ts');
const text = readFileSync(SRC, 'utf8');

const eqIdx = text.indexOf('=');
const start = text.indexOf('{', eqIdx);
const end = text.lastIndexOf('}');
if (eqIdx === -1 || start === -1 || end === -1) {
  throw new Error('abilities.ts: could not locate object literal');
}
// eslint-disable-next-line no-eval
const AbilitiesText = eval('(' + text.slice(start, end + 1) + ')');
console.log(`Loaded ${Object.keys(AbilitiesText).length} ability text entries from Showdown.`);

// 2. Build name → shortDesc from Showdown (skip the noability sentinel)

const showdownDesc = {};
for (const id of Object.keys(AbilitiesText)) {
  if (id === 'noability') continue;
  const entry = AbilitiesText[id];
  if (!entry || !entry.name) continue;
  const desc = entry.shortDesc ?? entry.desc;
  if (!desc) continue;
  showdownDesc[entry.name] = desc.trim();
}
console.log(`  Usable Showdown descriptions: ${Object.keys(showdownDesc).length}`);

// 3. Merge — curated wins, Showdown fills the gaps

const merged = { ...showdownDesc, ...CURATED };
const curatedCount = Object.keys(CURATED).length;
const addedCount = Object.keys(merged).length - curatedCount;
console.log(`  Curated kept: ${curatedCount} | filled from Showdown: ${addedCount} | total: ${Object.keys(merged).length}`);

// 4. Emit the TypeScript file (alphabetical, same shape as before)

function esc(s) {
  return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

const names = Object.keys(merged).sort((a, b) => a.localeCompare(b));

const lines = [];
lines.push('/** Short ability descriptions sourced from Pokemon Showdown data.');
lines.push(' *  Generated by scripts/gen-ability-desc.mjs — do not edit manually.');
lines.push(' *  (Curated entries are preserved across regen; Showdown fills the rest.) */');
lines.push('export const ABILITY_DESC: Record<string, string> = {');
for (const name of names) {
  lines.push(`  '${esc(name)}': '${esc(merged[name])}',`);
}
lines.push('};');
lines.push('');
lines.push('export function getAbilityDesc(name: string): string {');
lines.push("  return ABILITY_DESC[name] ?? 'No description available.';");
lines.push('}');
lines.push('');

const outPath = resolve(ROOT, 'src/lib/abilities.ts');
writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`\nWrote ${outPath} (${names.length} abilities)`);
