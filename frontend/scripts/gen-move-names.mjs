#!/usr/bin/env node
/**
 * Generates a Showdown move-ID → display-name map for the cannoli draft UI.
 *
 * Move data on the frontend is stored as Showdown move IDs (lowercase, no
 * spaces — e.g. `stealthrock`, `uturn`). This script builds the inverse:
 * a `{ moveId: "Display Name" }` table so the UI can render proper names.
 *
 * SCOPE: we only emit the move IDs that actually appear in
 * `src/data/pokemon-learnsets.ts` (the draft pool learnsets), not the entire
 * Showdown move dex. The learnset move IDs are the single-quoted tokens inside
 * the RAW_* `[string, string[]]` arrays. We regex every single-quoted token in
 * that file and keep only those that are real keys in moves.json — that filter
 * naturally drops Pokemon display names (e.g. 'Kommo-o') since they aren't move
 * keys.
 *
 * Source of names: the local Showdown checkout's moves.json, falling back to a
 * network fetch if the local file is missing.
 *
 * Usage: node scripts/gen-move-names.mjs
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
// Repo root is one level above the frontend dir (ROOT).
const REPO_ROOT = resolve(ROOT, '..');

// 1. Load the Showdown moves.json (id → { name, ... })

const LOCAL_MOVES = resolve(
  REPO_ROOT,
  'showdown/client/play.pokemonshowdown.com/data/moves.json',
);

function parseMovesText(text) {
  // The .json variant is plain JSON. Guard anyway: some Showdown data files are
  // JS modules (`exports.BattleMovedex = {...};`). Strip a leading assignment
  // and a trailing semicolon if JSON.parse fails outright.
  try {
    return JSON.parse(text);
  } catch {
    const start = text.indexOf('{');
    const end = text.lastIndexOf('}');
    if (start === -1 || end === -1) throw new Error('moves.json: no object literal found');
    return JSON.parse(text.slice(start, end + 1));
  }
}

let movesRaw;
if (existsSync(LOCAL_MOVES)) {
  console.log(`Loading moves from local file: ${LOCAL_MOVES}`);
  movesRaw = parseMovesText(readFileSync(LOCAL_MOVES, 'utf8'));
} else {
  console.log('Local moves.json not found — fetching from Showdown...');
  const res = await fetch('https://play.pokemonshowdown.com/data/moves.json');
  if (!res.ok) throw new Error(`Failed to fetch moves.json: ${res.status}`);
  movesRaw = parseMovesText(await res.text());
}

// Build id → display name.
const nameById = new Map();
for (const [id, data] of Object.entries(movesRaw)) {
  if (data && typeof data.name === 'string') nameById.set(id, data.name);
}
console.log(`  Loaded ${nameById.size} move names from moves.json.`);

// 2. Extract move IDs used by the draft-pool learnsets

const learnsetsSrc = readFileSync(resolve(ROOT, 'src/data/pokemon-learnsets.ts'), 'utf8');

// Every single-quoted token in the file. Pokemon names (which contain spaces,
// dashes, uppercase) won't be keys in moves.json and are dropped by the filter
// below.
const tokenRe = /'((?:[^'\\]|\\.)*)'/g;
const usedIds = new Set();
let m;
while ((m = tokenRe.exec(learnsetsSrc)) !== null) {
  const token = m[1];
  if (nameById.has(token)) usedIds.add(token);
}
console.log(`  Found ${usedIds.size} distinct move IDs in pokemon-learnsets.ts.`);

// 3. Emit src/data/move-names.ts

const sortedIds = [...usedIds].sort();

const lines = [];
lines.push('/**');
lines.push(' * Showdown move ID → display name. Generated by scripts/gen-move-names.mjs — do not edit manually.');
lines.push(' */');
lines.push('');
lines.push('export const MOVE_NAMES: Record<string, string> = {');
for (const id of sortedIds) {
  lines.push(`  ${JSON.stringify(id)}: ${JSON.stringify(nameById.get(id))},`);
}
lines.push('};');
lines.push('');
lines.push('export function moveDisplayName(id: string): string {');
lines.push('  return MOVE_NAMES[id] ?? id;');
lines.push('}');
lines.push('');

const outPath = resolve(ROOT, 'src/data/move-names.ts');
writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`\nWrote ${outPath}`);
console.log(`  Emitted ${sortedIds.length} move ID → name entries.`);
