#!/usr/bin/env bun
/**
 * Generates src/data/items.ts (full Showdown item list, display names) for Draft Center.
 * Drops CAP and Future items; Past (mega stones, Z-crystals, etc.) is kept for natdex.
 * Usage: bun scripts/gen-items.mjs [path/to/showdown/server/data/items.ts]
 */
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2] ?? resolve(root, '../showdown/server/data/items.ts');
const { Items } = await import(src);
const names = Object.values(Items)
  .filter(i => i.name && !['CAP', 'Future'].includes(i.isNonstandard))
  .map(i => i.name)
  .sort((a, b) => a.localeCompare(b));
const out = `/** Showdown item display names. Generated by scripts/gen-items.mjs — do not edit manually. */\nexport const ALL_ITEMS: string[] = ${JSON.stringify(names)};\n`;
writeFileSync(resolve(root, 'src/data/items.ts'), out);
console.log(`${names.length} items`);
